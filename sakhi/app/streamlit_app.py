"""Sakhi: Streamlit test frontend.

Run from the REPOSITORY ROOT (the folder that contains the `sakhi/` package):

    streamlit run sakhi/app/streamlit_app.py

Safety rules from the README that this app enforces:
  * "Call 112" is rendered before all other content when danger is likely.
  * A clear disclaimer (not an emergency service, not legal advice) is always shown.
  * User messages are never logged, written to disk, or kept in session state.
  * Low-confidence results show a safe fallback and ask for more detail.
  * Contact details come only from sakhi/config/helplines.yaml.
  * Legal explanations are fixed templates around retrieved official text.
"""
import csv
import importlib
import os
import sys
from pathlib import Path

import streamlit as st
import yaml

ROOT = Path(__file__).resolve().parents[2]  # repo root
PKG = ROOT / "sakhi"
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

CONFIG_PATH = PKG / "config" / "helplines.yaml"
SAMPLE_PATH = PKG / "data" / "raw" / "sample_fictional.csv"

URGENCY_ORDER = ["immediate_danger", "urgent", "non_urgent", "info_seeking"]
URGENCY_TEXT = {
    "immediate_danger": "Immediate danger",
    "urgent": "Urgent, act within days",
    "non_urgent": "Not urgent",
    "info_seeking": "Information request",
}

# Fixed, hand-written template. Nothing here is generated by a model.
PROVISION_TEMPLATE = (
    "**{act}, Section {section}** is official text that may relate to what you "
    "described. It is shown exactly as written. It is not a legal opinion and "
    "does not say whether an offence has taken place."
)

DISCLAIMER = (
    "Sakhi is a guidance and triage aid. It is **not an emergency service** and "
    "**not legal advice**. It never gives legal verdicts. Your message is not "
    "stored or logged."
)


# ----------------------------------------------------------------------------
# Config
# ----------------------------------------------------------------------------
@st.cache_resource
def load_config():
    if CONFIG_PATH.exists():
        with open(CONFIG_PATH, encoding="utf-8") as f:
            return yaml.safe_load(f), True
    # Fail-safe so the Call-112 banner can still render if the config is missing.
    return {"helplines": {"emergency": {"name": "Emergency number", "number": "112"}},
            "routing": {}, "fallback": ["emergency"]}, False


CFG, CFG_OK = load_config()
HELP = CFG.get("helplines", {})


def emergency_number():
    return HELP.get("emergency", {}).get("number", "112")


def render_contact(key):
    h = HELP.get(key)
    if not h:
        return
    line = f"**{h['name']}**"
    if h.get("number"):
        line += f": {h['number']}"
    if h.get("url"):
        line += f": {h['url']}"
    st.markdown(line)
    if h.get("notes"):
        st.caption(h["notes"])
    if h.get("verify_before_release", False):
        st.caption("⚠️ VERIFY BEFORE RELEASE")


# ----------------------------------------------------------------------------
# Backend adapter
# ----------------------------------------------------------------------------
# Contract: analyze(text: str) -> dict
#   {
#     "situations": [{"label": str, "prob": float, "predicted": bool}, ...],
#     "urgency":    {"label": str, "probs": {level: float, ...}},
#     "provisions": [{"act": str, "section": str, "text": str, "score": float}, ...],
#   }
@st.cache_resource
def get_backend():
    mod = importlib.import_module("sakhi.src.pipeline")
    if not mod.models_available():
        if os.environ.get("SAKHI_DEPLOYED", "").casefold() in {"1", "true", "yes"}:
            raise RuntimeError(
                "SAKHI_DEPLOYED is set but trained models are unavailable. "
                "Configure SAKHI_MODELS_DIR before starting the app."
            )
        return None, "No trained model configured"
    return getattr(mod, "analyze"), f"sakhi.src.pipeline.analyze ({mod.model_family()})"


analyze, BACKEND_NAME = get_backend()


# ----------------------------------------------------------------------------
# Test helpers
# ----------------------------------------------------------------------------
@st.cache_data
def load_samples():
    if not SAMPLE_PATH.exists():
        return []
    with open(SAMPLE_PATH, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


# ----------------------------------------------------------------------------
# Page
# ----------------------------------------------------------------------------
st.set_page_config(page_title="Sakhi", page_icon="🛡️", layout="centered")

# Reserved FIRST so the 112 banner can be filled after analysis but still appear above everything.
banner_slot = st.container()

st.title("🛡️ Sakhi")
st.caption("Women's safety triage and rights navigator. Hindi, Hinglish or English.")
st.info(DISCLAIMER)

with st.sidebar:
    st.header("Test settings")
    t112 = st.slider("Show Call 112 if P(immediate_danger) ≥", 0.05, 0.9, 0.25, 0.05,
                     help="Recall-first. Set this to the value you chose on the validation set.")
    conf_thr = st.slider("Low-confidence cutoff (top situation prob <)", 0.1, 0.9, 0.5, 0.05)
    show_details = st.checkbox("Show model details", value=True)
    use_sample = st.checkbox("Load a fictional sample message")
    st.caption(f"Backend: {BACKEND_NAME}")
    if not CFG_OK:
        st.warning("sakhi/config/helplines.yaml not found. Only the emergency number is available.")

sample = None
if use_sample:
    samples = load_samples()
    if samples:
        idx = st.sidebar.selectbox("Sample", range(len(samples)),
                                   format_func=lambda i: f"{samples[i]['id']} ({samples[i]['language']}, {samples[i]['urgency']})")
        sample = samples[idx]
    else:
        st.sidebar.warning("sample_fictional.csv not found.")

if analyze is None:
    st.error(
        "No trained model is available. Set SAKHI_MODELS_DIR to a trained model "
        "directory before using Sakhi."
    )

with st.form("sakhi_form", clear_on_submit=True):
    text = st.text_area("Tell Sakhi what is happening, in your own words",
                        value=sample["text"] if sample else "",
                        height=140,
                        placeholder="Hindi, Hinglish or English. A friend can write on her behalf.")
    submitted = st.form_submit_button("Get guidance", type="primary")

if sample:
    with st.sidebar.expander("Expected labels (test only)"):
        st.write({k: sample[k] for k in ("situation_labels", "urgency", "legal_refs", "perspective", "language")})

if submitted:
    text = (text or "").strip()
    if not text:
        st.warning("Please type a message first.")
        st.stop()

    if analyze is None:
        st.error("Guidance is unavailable until a trained model is configured.")
        st.stop()
    result = analyze(text)  # the message is never saved or logged
    urg = result["urgency"]
    probs = urg.get("probs", {})
    p_imm = probs.get("immediate_danger", 0.0)
    safety = result.get("safety", {})
    show_112 = (
        safety.get("rule_fired", False)
        or urg["label"] == "immediate_danger"
        or p_imm >= t112
    )

    # 1) Call 112 FIRST, above the title and disclaimer.
    if show_112:
        with banner_slot:
            st.error(
                f"## 📞 Call {emergency_number()} now\n"
                f"**If you are in danger right now, call {emergency_number()} first.**  \n"
                f"अगर आप अभी ख़तरे में हैं, तो तुरंत {emergency_number()} पर कॉल करें।"
            )

    sits = sorted(result["situations"], key=lambda s: -s["prob"])
    predicted = [s for s in sits if s.get("predicted", s["prob"] >= 0.5)]
    low_conf = (not sits) or sits[0]["prob"] < conf_thr

    st.divider()
    st.subheader("What Sakhi understood")
    st.markdown(f"**Urgency:** {URGENCY_TEXT.get(urg['label'], urg['label'])}")
    if safety.get("caring_message"):
        st.info(safety["caring_message"])
    for contact in safety.get("contacts", []):
        render_contact(contact["key"])

    if low_conf:
        # 2) Safe fallback.
        st.warning("I am not sure I understood this properly. Could you tell me a bit more? "
                   "For example: what happened, where, how often, and whether you are safe right now.")
        st.markdown("**General support you can reach now**")
        for key in CFG.get("fallback", ["emergency"]):
            render_contact(key)
    else:
        st.markdown("**Situation:** " + ", ".join(s["label"].replace("_", " ") for s in predicted))

        # 3) Retrieved law, shown via the fixed template.
        st.subheader("Relevant provisions")
        provisions = result.get("provisions", [])
        if safety.get("skip_legal_explanation"):
            st.info("Legal explanations are skipped while crisis support is the priority.")
        elif provisions:
            for p in provisions:
                st.markdown(
                    PROVISION_TEMPLATE.format(
                        act=p["act"], section=p.get("section_no", p.get("section", ""))
                    )
                )
                with st.expander("Official text"):
                    st.write(p["text"])
                    st.caption("Source: official legal text. Verify against India Code.")
        else:
            st.info("No matching provision was found.")

        # 4) Routing.
        st.subheader("Where to go")
        shown = []
        for s in predicted:
            for key in CFG.get("routing", {}).get(s["label"], []):
                if key not in shown:
                    shown.append(key)
        for key in shown:
            render_contact(key)

    if show_details:
        with st.expander("Model details (for testing)"):
            st.write("Situation probabilities", {s["label"]: round(s["prob"], 3) for s in sits})
            st.write("Urgency probabilities", {k: round(v, 3) for k, v in probs.items()})
            st.write({"show_112": show_112, "low_confidence": low_conf, "backend": BACKEND_NAME,
                      **result.get("meta", {})})

st.divider()
st.caption("Sakhi is not an emergency service and not legal advice. " 
           "Helpline details are marked VERIFY BEFORE RELEASE until checked.")